import AppKit

/// Full copy of a pasteboard's items, so a dictation pasted through ⌘V can give the user back what they had copied.
struct PasteboardSnapshot {
    let items: [[NSPasteboard.PasteboardType: Data]]

    init(of pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            var data: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types { data[type] = item.data(forType: type) }
            return data
        }
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let restored = items.map { values in
            let item = NSPasteboardItem()
            for (type, data) in values { item.setData(data, forType: type) }
            return item
        }
        if !restored.isEmpty { pasteboard.writeObjects(restored) }
    }
}

/// Puts dictated text on the pasteboard only for the paste, then restores the user's previous contents.
@MainActor
enum PasteboardRestore {
    /// Conventions from nspasteboard.org so clipboard managers skip the temporary dictation.
    static let transientTypes = [NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
                                 NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]

    private static var pending: (snapshot: PasteboardSnapshot, changeCount: Int, task: Task<Void, Never>)?

    /// Writes `text` for a paste and returns the snapshot to restore afterwards, or nil if writing failed.
    static func prepare(_ text: String, on pasteboard: NSPasteboard = .general) -> PasteboardSnapshot? {
        // A dictation still waiting to be restored is not the user's content; keep their original.
        let original: PasteboardSnapshot
        if let pending, pending.changeCount == pasteboard.changeCount {
            pending.task.cancel()
            original = pending.snapshot
        } else {
            pending?.task.cancel()
            original = PasteboardSnapshot(of: pasteboard)
        }
        pending = nil
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in transientTypes { item.setData(Data(), forType: type) }
        return pasteboard.writeObjects([item]) ? original : nil
    }

    /// Restores `snapshot` after `delay`, unless something else was copied in the meantime.
    static func restore(_ snapshot: PasteboardSnapshot, after delay: TimeInterval, on pasteboard: NSPasteboard = .general) {
        let changeCount = pasteboard.changeCount
        let task = Task { @MainActor in
            try? await Task.sleep(nanoseconds: UInt64(delay * 1_000_000_000))
            guard !Task.isCancelled, pasteboard.changeCount == changeCount else { return }
            snapshot.restore(to: pasteboard)
            if pending?.changeCount == changeCount { pending = nil }
        }
        pending = (snapshot, changeCount, task)
    }
}
